async function getDocxArchive(buffer) {
  return JSZip.loadAsync(buffer);
}

async function getDocxXml(buffer, path = 'word/document.xml') {
  const archive = await getDocxArchive(buffer);
  return archive.file(path).async('string');
}

function getPdfStreams(buffer) {
  const text = buffer.toString('latin1');
  return [...text.matchAll(/<< \/Length \d+ >>\nstream\n([\s\S]*?)endstream/g)]
    .map((match) => match[1])
    .filter((stream) => stream.includes('BT /'));
}

function getPdfText(buffer) {
  return getPdfStreams(buffer).map(getPdfStreamText).join(' ');
}

function getPdfStreamText(stream) {
  return [...stream.matchAll(/\(((?:\\.|[^\\)])*)\) Tj/g)]
    .map((match) => match[1].replace(/\\([\\()])/g, '$1'))
    .join(' ');
}

function pdfPageCount(buffer) {
  return Number(buffer.toString('latin1').match(/\/Type \/Pages[\s\S]*?\/Count (\d+)/)?.[1] || 0);
}

function getDocxTables(xml) {
  return [...xml.matchAll(/<w:tbl\b[\s\S]*?<\/w:tbl>/g)].map((match) => match[0]);
}

test('complete report fits one PDF page and generates a matching A4 Word package', async () => {
  const report = sampleReport(completeDetails);
  const normalized = getMaintenanceReportDetails(report);
  for (const [key, value] of Object.entries(completeDetails)) assert.equal(normalized[key], value);

  const pdf = createMaintenanceServicePdf(report);
  const pdfSource = pdf.toString('latin1');
  const pdfText = getPdfText(pdf);
  assert.equal(pdfPageCount(pdf), 1, 'A short complete report should fit on one A4 page.');
  for (const value of [
    'Republic of the Philippines', 'Mindoro State University', 'Bongabong Campus',
    'ComLab Facilities Management', 'MAINTENANCE SERVICE REPORT', 'TM-2026-0001',
    'November 1, 2026', 'Date submitted', '12:49 PM GMT+8', 'Reported issue or assigned task',
    'Inspection findings', 'Parts or materials used', 'Work performed', 'Outcome and verification',
    'Time (start - end)', '08:15 - 09:05', 'Recommended follow-up', 'JUAN P. DELA CRUZ',
    'MARIA S. SANTOS', 'Laboratory In-charge / Supervisor', 'Date:',
    'Generated by ComLab Facilities Management System'
  ]) assert.ok(pdfText.includes(value), `PDF is missing: ${value}`);
  assert.equal((pdfSource.match(/\/Subtype \/Image/g) || []).length, 2, 'PDF must embed both university and CCS logos.');
  assert.ok(pdfSource.includes('/MinSU Do') && pdfSource.includes('/CCS Do'));
  assert.ok(!pdfText.includes('Time started') && !pdfText.includes('Time completed'));
  assert.ok(!pdfText.includes('—') && !pdfText.includes('–'));
  const signatureStream = getPdfStreams(pdf).map(getPdfStreamText).find((stream) => stream.includes('Prepared by:'));
  assert.ok(signatureStream?.includes('Noted by:'), 'The complete signature block must stay together.');
  assert.ok(!pdfText.includes('Signatures') && !pdfText.includes('Date: ____________'));
  assert.ok(!signatureStream?.includes('________________'), 'Date underline text should be omitted.');
  assert.ok(pdfSource.includes('0.349 0.388 0.361 RG 0.5 w'), 'PDF should include signature lines above printed names.');

  const docx = await createMaintenanceServiceDocx(report);
  assert.equal(docx.subarray(0, 2).toString(), 'PK');
  const archive = await getDocxArchive(docx);
  const xml = await getDocxXml(docx);
  const footerXml = await getDocxXml(docx, 'word/footer1.xml');
  for (const value of [
    'Republic of the Philippines', 'Mindoro State University', 'Bongabong Campus',
    'ComLab Facilities Management', 'MAINTENANCE SERVICE REPORT', 'TM-2026-0001',
    'Reported issue or assigned task', 'Inspection findings', 'Parts or materials used',
    'Work performed', 'Outcome and verification', 'Time (start - end)', '08:15 - 09:05',
    'JUAN P. DELA CRUZ', 'MARIA S. SANTOS', 'Laboratory In-charge / Supervisor', 'Date:'
  ]) assert.ok(xml.includes(value), `Word is missing: ${value}`);
  assert.ok(!xml.includes('Time started') && !xml.includes('Time completed'));
  assert.ok(!xml.includes('—') && !xml.includes('–'));
  assert.equal(Object.keys(archive.files).filter((path) => path.startsWith('word/media/') && path !== 'word/media/').length, 2, 'Word letterhead must include both logos.');
  assert.ok(!xml.includes('Signatures') && !xml.includes('Date: ____________'));
  assert.ok(!xml.includes('________________'), 'Word date underline text should be omitted.');
  assert.ok(xml.includes('w:w="11906"') && xml.includes('w:h="16838"'), 'Word page must be A4 portrait.');
  assert.ok(xml.includes('w:left="1440"') && xml.includes('w:right="1440"'), 'Word page must use one-inch margins.');
  assert.ok(xml.includes('w:sz w:val="20"'), 'Table text should be 10 pt.');
  assert.ok(xml.includes('w:keepNext') && xml.includes('<w:cantSplit/>'));
  const tables = getDocxTables(xml);
  const infoTable = tables.find((table) => table.includes('Report ID'));
  const signatureTable = tables.find((table) => table.includes('Prepared by:'));
  assert.ok(infoTable);
  assert.ok(signatureTable?.includes('<w:pBdr>'), 'Word should include signature lines above printed names.');
  assert.ok(signatureTable?.includes('w:tblBorders'), 'Word signature columns should have visible box borders.');
  assert.equal((infoTable.match(/<w:tr>/g) || []).length, 3, 'Report Information must have exactly three rows.');
  assert.equal((infoTable.match(/<w:tc>/g) || []).length, 12, 'Report Information must use four columns.');
  assert.ok(signatureTable?.includes('<w:cantSplit/>'), 'The signature row must not split across pages.');
  assert.ok(!signatureTable?.includes('Approved by:'), 'The unassigned Approved by column must be omitted.');
  assert.ok(footerXml.includes('Report ID: TM-2026-0001'));
  assert.ok(footerXml.includes('Generated by ComLab Facilities Management System'));
  assert.ok(footerXml.includes('PAGE') && footerXml.includes('NUMPAGES'));
  assert.equal(formatMaintenanceReportId(2026, 1), 'TM-2026-0001');
});

test('reports without optional fields show N/A and keep one combined time row', async () => {
  const requiredOnly = {
    equipmentArea: 'COMLAB 1 · CPU-0042 — Desktop PC · Room 202',
    reportedIssue: 'Workstation does not start.',
    workPerformed: 'Checked the cable and restarted the computer.'
  };
  const report = sampleReport(requiredOnly, { recommendations: '', notedByName: '' });
  const details = getMaintenanceReportDetails(report);
  assert.equal(details.inspectionFindings, 'N/A');
  assert.equal(details.partsMaterialsUsed, 'N/A');
  assert.equal(details.outcomeVerification, 'N/A');
  assert.equal(details.timeStarted, 'N/A');
  assert.equal(details.timeCompleted, 'N/A');

  const pdf = createMaintenanceServicePdf(report);
  const pdfSource = pdf.toString('latin1');
  const pdfText = getPdfText(pdf);
  assert.equal(pdfPageCount(pdf), 1);
  assert.ok(pdfText.includes('Time (start - end)'));
  assert.ok(!pdfText.includes('Time started') && !pdfText.includes('Time completed'));
  assert.ok(pdfSource.includes('/F3 10 Tf') && pdfSource.includes('(N/A) Tj'), 'PDF N/A values should be gray and italic.');
  assert.ok(!pdfText.includes('________________'));
  assert.ok(pdfText.includes('Laboratory In-charge / Supervisor'));

  const xml = await getDocxXml(await createMaintenanceServiceDocx(report));
  assert.ok(xml.includes('Time (start - end)'));
  assert.ok(!xml.includes('Time started') && !xml.includes('Time completed'));
  assert.ok(xml.includes('N/A'));
  assert.ok(xml.includes('w:i'), 'Word N/A values should be italic.');
  assert.ok(xml.includes('8B918C'), 'Word N/A values should be light gray.');

  const legacy = sampleReport({}, {
    summary: 'Equipment / area\nOld COMLAB workstation · Room 202\n\nWork performed\nChecked the power connection and restarted the workstation.',
    recommendations: ''
  });
  assert.equal(getMaintenanceReportDetails(legacy).reportedIssue, 'N/A');
  assert.ok(getPdfText(createMaintenanceServicePdf(legacy)).includes('Old COMLAB workstation'));
  assert.ok((await getDocxXml(await createMaintenanceServiceDocx(legacy))).includes('Checked the power connection'));
});

test('long work continues on later pages and the whole signature block stays on one page', async () => {
  const longWork = `${'Replaced the worn component, tested the connection, and verified normal operation. '.repeat(50)}FINAL-CHECK-PASSED`;
  const report = sampleReport({ ...completeDetails, workPerformed: longWork });
  const pdf = createMaintenanceServicePdf(report);
  const streams = getPdfStreams(pdf);
  assert.ok(pdfPageCount(pdf) > 1, 'Long service details should continue to another page.');
  const streamText = streams.map(getPdfStreamText);
  const workPageIndex = streamText.findIndex((stream) => stream.includes('Work performed (continued)'));
  assert.ok(workPageIndex > 0, 'Long Work performed should continue on page 2 or later.');
  assert.ok(streamText.some((stream) => stream.includes('FINAL-CHECK-PASSED')));
  const signaturePage = streamText.find((stream) => stream.includes('Prepared by:'));
  assert.ok(signaturePage?.includes('Noted by:'), 'PDF signatures must remain together on one page.');
  assert.ok(streams.every((stream) => stream.includes('Page ') && stream.includes(' of ')), 'Every page needs a numbered footer.');

  const xml = await getDocxXml(await createMaintenanceServiceDocx(report));
  assert.ok(xml.includes('FINAL-CHECK-PASSED'));
  assert.ok(xml.includes('<w:cantSplit/>'));
  const signatureTable = getDocxTables(xml).find((table) => table.includes('Prepared by:'));
  assert.ok(signatureTable?.includes('<w:cantSplit/>'), 'The signature row must remain whole in Word.');
  assert.ok(signatureTable?.includes('w:keepNext'));
});

test('report date uses the selected ISO day and submitted timestamps use Asia/Manila', () => {
  assert.equal(formatReportDate('2026-11-01'), 'November 1, 2026');
  assert.equal(formatSubmittedAt(new Date('2026-11-01T04:49:00.000Z')), 'November 1, 2026 at 12:49 PM GMT+8');
});

test('maintenance documents reject a missing technician full name', async () => {
  const report = sampleReport(completeDetails, { technicianName: 'Technician' });
  assert.throws(() => createMaintenanceServicePdf(report), /full technician name/i);
  await assert.rejects(() => createMaintenanceServiceDocx(report), /full technician name/i);
});
